use crate::pipeline::decode::crc::{crc, CRCFunction};
use std::cmp::Ordering::Equal;

#[derive(Debug)]
enum Phase {
    L,
    R,
    U,
}

#[derive(Debug)]
struct Frame {
    start: usize,
    len: usize,
    layer: usize,
    phase: Phase,
}

#[derive(Clone)]
struct SCDecoderPath {
    pm: f32,
    u: Vec<u8>,
    u_tilde: Vec<u8>,
    llr_mem: Vec<f32>,
    crc_checksum: u32,
    crc_okay: bool,
}

/// Decodes the given llr values to a word matching the checksum. `input_interleaver` may either be
/// empty or an interleaver pattern to use on the returned contents.
/// If INIT_CRC_ONE is set, assumes the CRC is 1-initialized (requires a different syndrome).
/// Returns CRC mismatch if only the first eight crc bits are used.
/// The vector returned contains u, the decoded result.
pub fn ca_scl_decode<const L: usize, const FIRST_EIGHT_CRC_ONLY: bool, const INIT_CRC_ONE: bool>(
    llr: &[f32],
    k: usize,
    frozen: &[bool],
    input_interleaver: &[usize],
    crc_xor: u32
) -> Option<(u32, Vec<u8>)> {
    // Assumes N is power of two and llr size matches frozen size
    let n = llr.len();
    let crc_len = 24usize;

    let mut info_index_for_pos = vec![usize::MAX; n];
    let mut info_count = 0usize;
    for i in 0..n {
        if !frozen[i] {
            info_index_for_pos[i] = info_count;
            info_count += 1;
        }
    }

    let (crc_row_masks, crc_check_masks) = if k >= crc_len && info_count == k {
        build_crc_masks::<FIRST_EIGHT_CRC_ONLY>(k, input_interleaver)
    } else {
        (Vec::new(), Vec::new())
    };

    let crc_init = if INIT_CRC_ONE {
        // Recompute expected crc footprint for a 1-initialized crc with offset
        crc_init_all_ones(k) ^ (crc_xor.reverse_bits() >> 8)
    } else if crc_xor != 0 {
        crc_xor.reverse_bits() >> 8
    } else {
        0
    };

    // decisions
    let mut paths = Vec::with_capacity(L * 2);
    let u = vec![0u8; n];
    let u_tilde = vec![0u8; n];
    let mut llr_mem = vec![0f32; llr.len() * (n.ilog2() as usize + 1)];
    llr_mem[0..n].copy_from_slice(llr);
    paths.push(SCDecoderPath {
        pm: 0.0,
        u,
        u_tilde,
        llr_mem,
        crc_checksum: crc_init,
        crc_okay: true,
    });

    let mut stack = Vec::with_capacity(n);
    stack.push(Frame {
        start: 0,
        len: n,
        layer: 0,
        phase: Phase::L,
    });

    while let Some(mut frame) = stack.pop() {
        let start = frame.start;
        let len = frame.len;
        let layer = frame.layer;
        match frame.phase {
            Phase::L => {
                let h = len / 2;
                if len == 1 {
                    let info_idx = info_index_for_pos[start];
                    let crc_row_mask = if info_idx != usize::MAX && !crc_row_masks.is_empty() {
                        crc_row_masks[info_idx]
                    } else {
                        0
                    };
                    let crc_check_mask = if info_idx != usize::MAX && !crc_check_masks.is_empty() {
                        crc_check_masks[info_idx]
                    } else {
                        0
                    };
                    let path_count = paths.len();
                    for l in 0..path_count {
                        let path = &mut paths[l];
                        let lrr_i = path.llr_mem[layer * n + start];
                        if frozen[start] {
                            // u and u_tilde are already preset to 0
                            path.pm = phi(path.pm, lrr_i, 0);
                        } else {
                            // Fork paths
                            let mut path1 = path.clone();
                            // u and u_tilde are already preset to 0 on first path
                            path.pm = phi(path.pm, lrr_i, 0);
                            path1.u[start] = 1;
                            path1.u_tilde[start] = 1;
                            path1.pm = phi(path1.pm, lrr_i, 1);
                            path1.crc_checksum ^= crc_row_mask;
                            paths.push(path1);
                        }
                    }
                    // Sort and cut
                    paths.sort_by(|v1, v2| v1.pm.partial_cmp(&v2.pm).unwrap_or(Equal));
                    if paths.len() > L {
                        paths.drain(L..);
                    }
                    if crc_check_mask != 0 {
                        for path in &mut paths {
                            if path.crc_okay && (path.crc_checksum & crc_check_mask) != 0 {
                                path.crc_okay = false;
                            }
                        }
                        if !paths.iter().any(|p| p.crc_okay) {
                            // Early abort
                            return None;
                        }
                    }
                    // Skip the last stack elements if we reached the end
                    if start + 1 == n {
                        break;
                    }
                } else {
                    // Evaluate fast paths
                    let fseg = &frozen[start..start + len];
                    if fseg.iter().all(|&f| f) {
                        // Rate-0
                        // u and u_tilde are already preset to zero
                        for l in 0..paths.len() {
                            let path = &mut paths[l];
                            for i in start..start + len {
                                let lrr_i = path.llr_mem[layer * n + i];
                                path.pm = phi(path.pm, lrr_i, 0);
                            }
                        }
                        // Sort and cut
                        paths.sort_by(|v1, v2| v1.pm.partial_cmp(&v2.pm).unwrap_or(Equal));
                        if paths.len() > L {
                            paths.drain(L..);
                        }
                        // Skip the last stack elements if we reached the end
                        if start + len == n {
                            break;
                        }
                    } else {
                        // Compute left LLRs
                        for l in 0..paths.len() {
                            let path = &mut paths[l];
                            for i in 0..h {
                                let a = path.llr_mem[layer * n + start + i];
                                let b = path.llr_mem[layer * n + start + h + i];
                                path.llr_mem[(layer + 1) * n + start + i] = f_min_sum(a, b);
                            }
                        }
                        // Not decided yet -> continue
                        // Re-push current node to handle right after left
                        frame.phase = Phase::R;
                        stack.push(frame);
                        // Push left child
                        stack.push(Frame {
                            start,
                            len: h,
                            layer: layer + 1,
                            phase: Phase::L,
                        });
                    }
                }
            }
            Phase::R => {
                let h = len / 2;
                // compute right LLRs
                for path in &mut paths {
                    for i in 0..h {
                        let a = path.llr_mem[layer * n + start + i];
                        let b = path.llr_mem[layer * n + start + h + i];
                        let uleft = path.u_tilde[start + i];
                        path.llr_mem[(layer + 1) * n + start + h + i] = g_min_sum(a, b, uleft);
                    }
                }
                frame.phase = Phase::U;
                stack.push(frame);
                stack.push(Frame {
                    start: start + h,
                    len: h,
                    layer: layer + 1,
                    phase: Phase::L,
                });
            }
            Phase::U => {
                // Combine beliefs
                let h = len / 2;
                for path in &mut paths {
                    for i in 0..h {
                        path.u_tilde[start + i] ^= path.u_tilde[start + h + i];
                    }
                }
            }
        }
    }

    // Use the best path that matches CRC
    let mut temp = vec![0u8; n];
    paths.sort_by(|v1, v2| v1.pm.partial_cmp(&v2.pm).unwrap_or(Equal));
    for path in paths {
        if !path.crc_okay {
            continue;
        }
        // Remove frozen bits
        let mut u: Vec<u8> = path
            .u
            .into_iter()
            .zip(frozen.iter())
            .filter_map(|(val, &m)| if m { None } else { Some(val) })
            .collect();

        // Interleaver support
        if !input_interleaver.is_empty() {
            for i in 0..input_interleaver.len() {
                temp[input_interleaver[i]] = u[i];
            }

            if !crc_check_masks.is_empty() {
                debug_assert!(path.crc_okay, "incremental CRC marked path invalid");
            }

            // Return result
            if FIRST_EIGHT_CRC_ONLY {
                // In case of not known RNTI in shared decoding mode we extract the crc mismatch
                // to get RNTI.
                let mut path_crc = 0u32;
                for (i, p) in (k-crc_len..k).enumerate() {
                    if temp[p] == 1 {
                        path_crc |= 1u32 << i;
                    }
                }
                temp.drain(k - crc_len..);

                let actual_crc = crc(temp.as_slice(), CRCFunction::GCrc24c);
                let mut crc_append = 0u32;
                for p in 0..crc_len {
                    if actual_crc[p] == 1 {
                        crc_append |= 1u32 << p;
                    }
                }

                return Some(((path_crc ^ crc_append) & 0xFFFF, temp));
            } else {
                temp.drain(k - crc_len..);
                return  Some((0, temp));
            }
        } else {
            if !crc_check_masks.is_empty() {
                debug_assert!(path.crc_okay, "incremental CRC marked path invalid");
            }

            // Return result
            if FIRST_EIGHT_CRC_ONLY {
                // In case of not known RNTI in shared decoding mode we extract the crc mismatch
                // to get RNTI.
                let mut path_crc = 0u32;
                for (i, p) in (k-crc_len..k).enumerate() {
                    if u[p] == 1 {
                        path_crc |= 1u32 << i;
                    }
                }
                u.drain(k - crc_len..);

                let actual_crc = crc(u.as_slice(), CRCFunction::GCrc24c);
                let mut crc_append = 0u32;
                for p in 0..crc_len {
                    if actual_crc[p] == 1 {
                        crc_append |= 1u32 << p;
                    }
                }

                return Some(((path_crc ^ crc_append) & 0xFFFF, u));
            } else {
                u.drain(k - 24..);
                return  Some((0, u));
            }
        }
    }

    // No decoding result matched CRC
    None
}

fn crc_init_all_ones(k: usize) -> u32 {
    let bits = Vec::from_iter((0..24).map(|_| 1).chain((0..k-24).map(|_| 0)));
    let crc_bits = crc(bits.as_slice(), CRCFunction::GCrc24c);

    let mut offset = 0u32;
    for p in 0..24 {
        if crc_bits[p] == 1 {
            offset |= 1u32 << p;
        }
    }
    offset
}

#[inline]
fn f_min_sum(a: f32, b: f32) -> f32 {
    a.signum() * b.signum() * a.abs().min(b.abs())
}

#[inline]
fn g_min_sum(a: f32, b: f32, u: u8) -> f32 {
    b + (1f32 - 2f32 * u as f32) * a
}

#[inline(always)]
fn phi(pm: f32, l_i: f32, u_i: u8) -> f32 {
    // u_i == 1/2 * (1 - l_i.signum())
    let b = u_i as f32 - 0.5 * (1.0 - l_i.signum());
    // Both l_i and b might be positive or negative, but the path metric should always be penalized
    // when b != 0 (mismatch with u_i)
    pm + (l_i * b).abs()
}

fn build_crc_masks<const FIRST_EIGHT_CRC_ONLY: bool>(k: usize, input_interleaver: &[usize]) -> (Vec<u32>, Vec<u32>) {
    let crc_len = 24usize;
    let a = k.saturating_sub(crc_len);
    let crc_interleaver: Vec<usize> = if input_interleaver.is_empty() {
        (0..k).collect()
    } else {
        input_interleaver.to_vec()
    };

    let mut info_crc_rows: Vec<u32> = Vec::with_capacity(a);
    for i in 0..a {
        let mut bits = vec![0u8; a];
        bits[i] = 1;
        let crc_bits = crc(&bits, CRCFunction::GCrc24c);
        let mut mask = 0u32;
        for p in 0..crc_len {
            if crc_bits[p] == 1 {
                mask |= 1u32 << p;
            }
        }
        info_crc_rows.push(mask);
    }

    let mut crc_row_masks = Vec::with_capacity(k);
    for i2 in 0..k {
        let orig = crc_interleaver[i2];
        let mask = if orig < a {
            info_crc_rows[orig]
        } else {
            1u32 << (orig - a)
        };
        crc_row_masks.push(mask);
    }

    let mut last_one_index = vec![usize::MAX; crc_len];
    for i2 in 0..k {
        let mask = crc_row_masks[i2];
        for p in 0..crc_len {
            if ((mask >> p) & 1) == 1 {
                last_one_index[p] = i2;
            }
        }
    }

    let mut crc_check_masks = vec![0u32; k];
    for p in 0..crc_len {
        let idx = last_one_index[p];
        if idx != usize::MAX {
            crc_check_masks[idx] |= 1u32 << p;
        }
    }

    if FIRST_EIGHT_CRC_ONLY {
        crc_check_masks.iter_mut().for_each(|c| *c &= 0x00FF_0000);
    }

    (crc_row_masks, crc_check_masks)
}

